class TestLogSanityAndStress:
    """Inspect compilation logs for overfull boxes or critical warnings."""

    def test_no_severe_margin_overflow(self):
        """Verify that no overfull hbox exceeds 25pt (which would visibly clip page borders)."""
        log_file = os.path.join(REPORT_DIR, "main_d2.log")
        assert os.path.exists(log_file), "Log file must exist"
        with open(log_file, "r", encoding="utf-8", errors="ignore") as f:
            log = f.read()

        overfull_matches = re.findall(r'Overfull \\hbox \((\d+\.?\d*)pt too wide\)', log)
        for val_str in overfull_matches:
            val = float(val_str)
            assert val < 25.0, f"Severe overfull hbox found ({val}pt too wide > 25pt limit)!"

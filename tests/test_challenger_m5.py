class TestCleanCompilationStress:
    """Empirical challenge of LaTeX compilation from a completely clean state."""

    def test_clean_scratch_compilation(self, tmp_path):
        """Verify 4-pass pdflatex + bibtex build exits 0 from an isolated clean scratch directory."""
        import shutil
        scratch_dir = tmp_path / "scratch_report_d2"
        shutil.copytree(
            REPORT_DIR,
            str(scratch_dir),
            ignore=shutil.ignore_patterns("*.aux", "*.bbl", "*.blg", "*.log", "*.out", "*.pdf", "*.run.xml", "*-blx.bib", "*.toc")
        )

        pdf_target = scratch_dir / "main_d2.pdf"
        assert not pdf_target.exists(), "PDF should not exist in clean scratch dir"

        # Pass 1: Initial pdflatex
        cmd1 = ["pdflatex", "-interaction=nonstopmode", "main_d2.tex"]
        p1 = subprocess.run(cmd1, cwd=str(scratch_dir), capture_output=True, text=True)
        assert p1.returncode == 0, f"Pass 1 pdflatex failed: {p1.stderr}\n{p1.stdout[-1000:]}"
        assert (scratch_dir / "main_d2.aux").exists(), "main_d2.aux must be generated in pass 1"

        # Pass 2: BibTeX
        cmd2 = ["bibtex", "main_d2"]
        p2 = subprocess.run(cmd2, cwd=str(scratch_dir), capture_output=True, text=True)
        assert p2.returncode == 0, f"Pass 2 bibtex failed: {p2.stderr}\n{p2.stdout[-1000:]}"
        assert (scratch_dir / "main_d2.bbl").exists(), "main_d2.bbl must be generated by bibtex"

        # Pass 3: Second pdflatex (resolves bibliography)
        cmd3 = ["pdflatex", "-interaction=nonstopmode", "main_d2.tex"]
        p3 = subprocess.run(cmd3, cwd=str(scratch_dir), capture_output=True, text=True)
        assert p3.returncode == 0, f"Pass 3 pdflatex failed: {p3.stderr}\n{p3.stdout[-1000:]}"

        # Pass 4: Third pdflatex (resolves cross-references and page counters)
        cmd4 = ["pdflatex", "-interaction=nonstopmode", "main_d2.tex"]
        p4 = subprocess.run(cmd4, cwd=str(scratch_dir), capture_output=True, text=True)
        assert p4.returncode == 0, f"Pass 4 pdflatex failed: {p4.stderr}\n{p4.stdout[-1000:]}"

        assert pdf_target.exists(), "PDF must exist after clean compilation"
        file_size = pdf_target.stat().st_size
        assert file_size > 100_000, f"PDF file size {file_size} is unexpectedly small (<100KB)"

    def test_makefile_report_d2_target(self):
        """Verify that 'make report_d2' runs to completion with exit code 0."""
        res = subprocess.run(["make", "report_d2"], cwd=REPO_ROOT, capture_output=True, text=True)
        assert res.returncode == 0, f"'make report_d2' failed with code {res.returncode}:\n{res.stderr}\n{res.stdout[-1000:]}"


class TestPdfDocumentStructure:
    """Empirical verification of PDF page bounds, geometry, and layout completeness."""

    @pytest.fixture
    def pdf_reader(self):
        assert os.path.exists(PDF_FILE), f"PDF {PDF_FILE} must exist"
        with open(PDF_FILE, "rb") as f:
            pdf_bytes = io.BytesIO(f.read())
        return pypdf.PdfReader(pdf_bytes)

    def test_page_count_strictly_4_to_6(self, pdf_reader):
        """The course CO5151 syllabus strictly mandates a 4-6 page limit for Deliverable 2."""
        num_pages = len(pdf_reader.pages)
        assert 4 <= num_pages <= 6, f"Page count {num_pages} violates the strict [4, 6] page constraint!"
        assert num_pages == 6, f"Expected exactly 6 pages (1 title page + 5 content pages), got {num_pages}"

    def test_each_page_has_substantial_content(self, pdf_reader):
        """Verify that every single page contains non-empty, substantial extracted text."""
        for idx, page in enumerate(pdf_reader.pages):
            text = page.extract_text()
            assert text is not None and len(text.strip()) > 300, (
                f"Page {idx+1} has insufficient content ({len(text) if text else 0} chars)"
            )

    def test_pagination_headers_and_footers(self, pdf_reader):
        """Verify proper HCMUT course headers and formal Page X/5 footers on content pages."""
        # Page 1 is title page
        p1_text = pdf_reader.pages[0].extract_text()
        assert "VIETNAM NATIONAL UNIVERSITY" in p1_text
        assert "CO5151" in p1_text
        assert "Lê Xuân Bách" in p1_text
        assert "Group 8" in p1_text

        # Content pages 2-6 have footers Page 1/5 through Page 5/5
        for i in range(1, 6):
            page_text = pdf_reader.pages[i].extract_text()
            assert "CO5151" in page_text, f"Missing CO5151 header on content page {i}"
            expected_footer = f"Page {i}/5"
            assert expected_footer in page_text, f"Expected '{expected_footer}' in page {i+1} text"


class TestDocumentQualityAndReadability:
    """Empirical audit of text rendering, cross-references, citations, and placeholders."""

    @pytest.fixture
    def pdf_full_text(self):
        assert os.path.exists(PDF_FILE), f"PDF {PDF_FILE} must exist"
        with open(PDF_FILE, "rb") as f:
            pdf_bytes = io.BytesIO(f.read())
        reader = pypdf.PdfReader(pdf_bytes)
        return "\n".join([p.extract_text() for p in reader.pages])

    @pytest.fixture(scope="class")
    def tex_content(self):
        with open(TEX_FILE, "r", encoding="utf-8") as f:
            return f.read()

    def test_zero_broken_citation_or_reference_marks(self, pdf_full_text):
        """Verify that no unresolved citation '[?]' or broken cross-reference '??' exists."""
        broken_cites = re.findall(r'\[\?\]', pdf_full_text)
        broken_refs = re.findall(r'\?\?', pdf_full_text)
        assert len(broken_cites) == 0, f"Found unresolved citations in PDF: {broken_cites}"
        assert len(broken_refs) == 0, f"Found broken cross-references '??' in PDF: {broken_refs}"

    def test_zero_placeholder_tokens_in_source_and_pdf(self, tex_content, pdf_full_text):
        """Verify that no draft placeholders like [TBD], [TODO], XX%, FILLME exist."""
        forbidden = [r'\[TBD\]', r'\[TODO\]', r'XX%', r'FILLME', r'FIXME']
        for pat in forbidden:
            assert not re.search(pat, tex_content), f"Found placeholder {pat} in LaTeX source"
            assert not re.search(pat, pdf_full_text), f"Found placeholder {pat} in PDF text"

    def test_all_12_citations_resolved_and_printed(self, pdf_full_text):
        """Verify that all citations [1] through [12] are cited and printed in the References."""
        found_citations = set(re.findall(r'\[(\d+)\]', pdf_full_text))
        for num in range(1, 13):
            assert str(num) in found_citations, f"Citation [{num}] is missing from the document"

        # Check references header and sample bibliography items
        assert "References" in pdf_full_text
        assert "Law on Personal Data Protection, Law No. 91/2025/QH15" in pdf_full_text
        assert "Decree No. 356/2025/ND-CP" in pdf_full_text
        assert "VLQA" in pdf_full_text

    def test_all_tables_and_figures_numbered_and_referenced(self, pdf_full_text):
        """Verify that Tables 1-5 and Figure 1 are referenced and captioned with explicit numbers."""
        for t_idx in range(1, 6):
            assert f"Table {t_idx}" in pdf_full_text, f"Table {t_idx} reference missing in PDF"
        assert "Figure 1" in pdf_full_text, "Figure 1 reference missing in PDF"



"""Render the Mac latency table (deliverables/d2/report/benchmark_latency_mac.tex) from a mac-latency run's analysis/summary.json.

Companion of evaluation/render_benchmark_tables.py (which renders the accuracy tables of one run): the report takes accuracy from the
GPU run and latency/memory from the Mac run, so the latency columns of the Mac run get their own table. Values come only from the
summary; a missing value is a red [PENDING]. Refuses a non-reportable-latency or non-eligible run unless --allow-non-eligible
(then the caption carries a red banner and the file must not be copied into deliverables/d2/report/).

  .venv/bin/python deliverables/d2/report/make_latency_table.py --run-dir evaluation/runs/<mac run> [--output deliverables/d2/report/benchmark_latency_mac.tex]
"""
import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO / "evaluation"))
import render_benchmark_tables as rt  # noqa: E402

BENCHES, VARIANTS = ["hcmut_v1", "labour_vi_v1"], ["off", "l1", "l1_rerank"]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--output", default=str(REPO / "deliverables/d2/report" / "benchmark_latency_mac.tex"))
    ap.add_argument("--allow-non-eligible", action="store_true")
    a = ap.parse_args()
    s = json.loads((Path(a.run_dir) / "analysis" / "summary.json").read_text(encoding="utf-8"))
    banner = ""
    if not s["latency_reportable"]:
        raise SystemExit("This run did not record reportable (sequential) latency; use the mac-latency profile run.")
    latency_only = s.get("judge_model") is None and s.get("phase") == "main" and s["coverage"]["planned"] == s["coverage"]["recorded"]
    if not s["report_eligible"] and not latency_only:
        if not a.allow_non_eligible:
            raise SystemExit("Run is not report-eligible: " + str(s.get("report_eligible_note")))
        banner = r"\textcolor{red}{\textbf{NON-ELIGIBLE RUN (" + rt.esc(s["phase"]) + r"): not report evidence.}} "
    elif not s["report_eligible"]:
        banner = "Latency only (no judge). "
    rows = []
    for b in BENCHES:
        for i, v in enumerate(VARIANTS):
            c = s["cells"].get(f"{b}/{v}")
            lead = rf"\multirow{{{len(VARIANTS)}}}{{*}}{{{rt.esc(rt.BENCH_NAMES.get(b, b))}}}" if i == 0 else ""
            name = rt.esc(rt.VARIANT_NAMES.get(v, v)).replace("+", "{+}")
            if c is None:
                rows.append(f"{lead} & {name} & " + " & ".join([rt.PENDING] * 6) + r"\\")
                continue
            lat = c["latency"]
            rer = "--" if v != "l1_rerank" else (rt.PENDING if lat.get("rerank_call_p50_s") is None else f"{lat['rerank_call_p50_s']:.2f}")
            rows.append(" & ".join([
                lead, name, str(c["trials_recorded"]), rt.pct(c["errors"]["error_rate"]),
                rt.pair_cell(lat, "trial_p50_s", "trial_p95_s"), rt.pair_cell(lat, "model_call_p50_s", "model_call_p95_s", 2),
                rt.num(lat.get("decode_tokens_per_s_p50"), 0), rer]) + r"\\")
        rows.append(r"\midrule")
    rows.pop()
    mem = s.get("peak_memory_mb") or {}
    def mb(k):
        return rt.PENDING if mem.get(k) is None else f"{mem[k]:.0f}"
    caption = (banner + f"Latency and memory on the Apple M4 (16\\,GiB, Metal), run {rt.esc(s['run_id'])}: sequential, warm-up excluded; percentiles over non-error trials, execution errors count only in Err. "
               "Trial = whole agent run; call = one controller request. The GGUF reranker is not the runtime of the accuracy run, so accuracy is never pooled across machines. "
               f"Peak resident memory: llama-server {mb('llama_server_rss_sampled')}\\,MB, runner {mb('runner_rss_sampled')}\\,MB (sampled).")
    out = "\n".join([
        f"% Generated by deliverables/d2/report/make_latency_table.py from {s['run_id']} ({s['phase']}). Do not edit by hand.",
        r"\begin{table}[t]\centering\scriptsize\setlength{\tabcolsep}{3pt}", r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{@{}llrrrrrr@{}}\toprule",
        r"Benchmark & Variant & Trials & Err.\ (\%) & Trial p50/p95 (s) & Call p50/p95 (s) & Decode tok/s & Rerank call p50 (s)\\\midrule",
        *rows, r"\bottomrule\end{tabular}}", r"\caption{" + caption + "}", r"\label{tab:benchmark-latency}", r"\end{table}", ""])
    prov = rt.provenance_for(Path(a.run_dir), s, "deliverables/d2/report/make_latency_table.py --run-dir " + str(Path(a.run_dir).as_posix()))
    out = rt.tag_tables(out, prov)
    Path(a.output).write_text(out, encoding="utf-8")
    print("wrote", a.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
